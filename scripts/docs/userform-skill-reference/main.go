// Command userform-skill-reference renders the bundled skill's property contract.
package main

import (
	"fmt"
	"maps"
	"slices"
	"strconv"
	"strings"

	"github.com/harumiWeb/xlflow/internal/vba/userforms/spec"
)

func main() {
	fmt.Print(render())
}

func render() string {
	contract := spec.UserFormContract()
	var b strings.Builder
	b.WriteString("# FormSpec Property Contract\n\n")
	b.WriteString("Generated from xlflow's shared UserForm contract. Read [property guidance](forms-properties.md) for examples, edit semantics and compiler limits. Do not edit this file by hand; maintainers regenerate it with `pnpm docs:generate-form-skill`.\n\n")
	b.WriteString("Use the exact camelCase keys below. `stringArray` means an array of strings; `objectArray` means an array of objects. Required fields are required when the enclosing object exists. A dash in Values means this metadata lists no finite set; additional semantic and compiler validation still applies. `any` does not promise persistence of arbitrary values. Snapshot-only fields are captured metadata, not edit requests, except legacy nested `controls`, which is accepted as input and normalized to the canonical flat root `controls` array. Use the flat format for new authoring.\n\n")
	b.WriteString("## Contents\n\n- [Document](#document)\n- [Form](#form)\n- [Common control fields](#common-control-fields)\n- [Control types and hierarchy](#control-types-and-hierarchy)\n- [Control properties by type](#control-properties-by-type)\n- [Nested objects](#nested-objects)\n- [TabStrip tab records](#tabstrip-tab-records)\n\n")
	properties(&b, "Document", contract.DocumentProperties)
	properties(&b, "Form", contract.FormProperties)
	properties(&b, "Common control fields", contract.CommonControlProperties)
	b.WriteString("Page excludes common geometry fields as listed below. Omit parentId for form-root controls. Use a flat controls array, not nested child arrays.\n\n")
	b.WriteString("## Control types and hierarchy\n\n")
	rows := [][]string{{"Type", "Default progId", "Children", "Required parent type", "Excluded common fields"}}
	for _, key := range slices.Sorted(maps.Keys(contract.Controls)) {
		control := contract.Controls[key]
		children := "None"
		if control.CanContainChildren {
			children = "Permitted controls"
			if len(control.AllowedChildTypes) > 0 {
				children = strings.Join(control.AllowedChildTypes, ", ")
			}
		}
		parent := "Form root or permitted container"
		if len(control.AllowedParentTypes) > 0 {
			parent = strings.Join(control.AllowedParentTypes, ", ")
		}
		rows = append(rows, []string{code(control.Type), code(control.ProgID), children, parent, choices(control.ExcludedCommonProperties)})
	}
	table(&b, rows)
	b.WriteString("## Control properties by type\n\n")
	b.WriteString("These fields extend the common fields. A property absent from a type's row set is not a modeled top-level property for that type. Parent/child restrictions and supported binary state are also checked by the compiler.\n\n")
	rows = [][]string{{"Property", "Type", "Support", "Values", "Applies to", "Meaning"}}
	type group struct {
		property spec.PropertyContract
		controls []string
	}
	groups := map[string]*group{}
	for _, key := range slices.Sorted(maps.Keys(contract.Controls)) {
		control := contract.Controls[key]
		for _, name := range slices.Sorted(maps.Keys(control.Properties)) {
			p := control.Properties[name]
			identity := name + "|" + string(p.ValueType) + "|" + string(p.SupportLevel) + "|" + values(p) + "|" + p.Description
			if groups[identity] == nil {
				groups[identity] = &group{property: p}
			}
			groups[identity].controls = append(groups[identity].controls, control.Type)
		}
	}
	for _, key := range slices.Sorted(maps.Keys(groups)) {
		name, _, _ := strings.Cut(key, "|")
		g := groups[key]
		rows = append(rows, []string{code(name), string(g.property.ValueType), string(g.property.SupportLevel), values(g.property), strings.Join(g.controls, ", "), g.property.Description})
	}
	table(&b, rows)
	b.WriteString("## Nested objects\n\n")
	propertiesAtLevel(&b, "font members", contract.FormProperties["font"].Children, 3)
	propertiesAtLevel(&b, "foreColor and backColor members", contract.FormProperties["foreColor"].Children, 3)
	propertiesAtLevel(&b, "Image picture actions", spec.PictureActionProperties(), 3)
	b.WriteString("picture requires exactly one action: path or remove: true. See [property guidance](forms-properties.md#pictures) for asset constraints.\n\n")
	properties(&b, "TabStrip tab records", contract.TabProperties)
	return b.String()
}

func properties(b *strings.Builder, title string, entries map[string]spec.PropertyContract) {
	propertiesAtLevel(b, title, entries, 2)
}

func propertiesAtLevel(b *strings.Builder, title string, entries map[string]spec.PropertyContract, level int) {
	fmt.Fprintf(b, "%s %s\n\n", strings.Repeat("#", level), title)
	rows := [][]string{{"Field", "Type", "Required", "Support", "Values", "Meaning"}}
	for _, name := range slices.Sorted(maps.Keys(entries)) {
		p := entries[name]
		rows = append(rows, []string{code(name), string(p.ValueType), strconv.FormatBool(p.Required), string(p.SupportLevel), values(p), p.Description})
	}
	table(b, rows)
}

func values(p spec.PropertyContract) string {
	parts := []string{}
	if len(p.AllowedValues) > 0 {
		parts = append(parts, choices(p.AllowedValues))
	}
	if p.Minimum != nil {
		op := ">= "
		if p.ExclusiveMinimum {
			op = "> "
		}
		parts = append(parts, op+strconv.FormatFloat(*p.Minimum, 'f', -1, 64))
	}
	if p.Maximum != nil {
		parts = append(parts, "<= "+strconv.FormatFloat(*p.Maximum, 'f', -1, 64))
	}
	if len(parts) == 0 {
		return "—"
	}
	return strings.Join(parts, "; ")
}

func choices(items []string) string {
	if len(items) == 0 {
		return "—"
	}
	result := make([]string, len(items))
	for i, item := range items {
		result[i] = code(item)
	}
	return strings.Join(result, ", ")
}

func code(s string) string { return "`" + s + "`" }

func table(b *strings.Builder, rows [][]string) {
	write := func(row []string) {
		cells := make([]string, len(row))
		for i, cell := range row {
			cells[i] = strings.ReplaceAll(cell, "|", "\\|")
		}
		fmt.Fprintf(b, "| %s |\n", strings.Join(cells, " | "))
	}
	write(rows[0])
	separator := make([]string, len(rows[0]))
	for i := range separator {
		separator[i] = "---"
	}
	write(separator)
	for _, row := range rows[1:] {
		write(row)
	}
	b.WriteString("\n")
}
